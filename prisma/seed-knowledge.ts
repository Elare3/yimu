async function seed() {
  console.log('🌱 开始灌入知识库文档...\n');

  let created = 0;
  let updated = 0;

  for (const doc of knowledgeDocs) {
    const existing = await prisma.knowledgeDoc.findUnique({
      where: { slug: doc.slug },
    });

    if (existing) {
      await prisma.knowledgeDoc.update({
        where: { slug: doc.slug },
        data: {
          ...doc,
          version: existing.version + 1,
        },
      });
      updated++;
      console.log(`  ✏️  更新: ${doc.title}`);
    } else {
      await prisma.knowledgeDoc.create({
        data: doc,
      });
      created++;
      console.log(`  ✅ 新增: ${doc.title}`);
    }
  }

  console.log(`\n🎉 完成！新增 ${created} 篇，更新 ${updated} 篇，共 ${knowledgeDocs.length} 篇知识文档。`);
}

seed()
  .catch((e) => {
    console.error('❌ Seed 失败:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
